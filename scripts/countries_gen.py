#!/usr/bin/env python3
"""Generates the country tables for Android (Kotlin) and Windows (Go) from scripts/countries.tsv.
With --flags it also downloads the flag SVGs (flag-icons, MIT) for the Windows UI."""
import os, sys, urllib.request

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rows = []
for line in open(os.path.join(root, "scripts/countries.tsv"), encoding="utf-8"):
    if not line.strip() or line.startswith("#"):
        continue
    parts = line.rstrip("\n").split("\t")
    parts += [""] * (4 - len(parts))
    code, de, en, more = parts[:4]
    aliases = [a.strip() for a in more.split(",") if a.strip()]
    rows.append((code, de, en, aliases))

def kstr(s): return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'

kt = ["// Generated by scripts/countries_gen.py from scripts/countries.tsv – do not edit.",
      "package dev.shield.core.vpn", "", "internal val COUNTRY_DATA: List<Country> = listOf("]
for code, de, en, al in rows:
    kt.append(f"    Country({kstr(code)}, {kstr(de)}, {kstr(en)}, listOf({', '.join(kstr(a) for a in al)})),")
kt.append(")")
open(os.path.join(root, "app/src/main/java/dev/shield/core/vpn/CountryData.kt"), "w", encoding="utf-8").write("\n".join(kt) + "\n")

go = ["// Code generated by scripts/countries_gen.py from scripts/countries.tsv; DO NOT EDIT.", "", "package app", "",
      "var countryData = []Country{"]
for code, de, en, al in rows:
    go.append('\t{%s, %s, %s, []string{%s}},' % (kstr(code), kstr(de), kstr(en), ", ".join(kstr(a) for a in al)))
go.append("}")
open(os.path.join(root, "desktop/internal/app/countries_data.go"), "w", encoding="utf-8").write("\n".join(go) + "\n")

if "--flags" in sys.argv:
    out = os.path.join(root, "desktop/internal/web/static/flags")
    os.makedirs(out, exist_ok=True)
    for code, *_ in rows:
        url = f"https://raw.githubusercontent.com/lipis/flag-icons/main/flags/4x3/{code.lower()}.svg"
        data = urllib.request.urlopen(url, timeout=30).read()
        if not data.lstrip().startswith(b"<svg") or b"<script" in data.lower():
            sys.exit(f"unexpected content for {code}")
        open(os.path.join(out, code.lower() + ".svg"), "wb").write(data)
    print("flags:", len(rows))
print("countries:", len(rows))
